-- Per-month income receipts; existing plans, payments and trackers are not rewritten.
begin;
create table public.income_receipts (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 income_id bigint not null references public.income_sources(id) on delete cascade,
 period_year integer not null check(period_year between 1900 and 9999),
 period_month integer not null check(period_month between 1 and 12),
 due_date date not null,
 expected_amount numeric(14,2) not null check(expected_amount>=0 and expected_amount<1000000000000),
 actual_amount numeric(14,2) not null check(actual_amount>=0 and actual_amount<1000000000000),
 is_received boolean not null,
 note text not null default '' check(length(note)<=2000),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 unique(user_id,income_id,period_year,period_month),
 check(extract(year from due_date)=period_year and extract(month from due_date)=period_month)
);
alter table public.income_receipts enable row level security;
revoke all on public.income_receipts from public,anon,authenticated;
grant select,insert,update on public.income_receipts to authenticated;
grant usage,select on sequence public.income_receipts_id_seq to authenticated;
create policy income_receipt_own on public.income_receipts for all to authenticated
 using(user_id=auth.uid()) with check(user_id=auth.uid() and exists(select 1 from public.income_sources s where s.id=income_id and s.user_id=auth.uid()));
create function public.save_income_receipt(p_income_id bigint,p_period_year integer,p_period_month integer,p_due_date date,p_expected_amount numeric,p_actual_amount numeric,p_is_received boolean,p_note text,p_expected_user_id uuid)
returns jsonb language plpgsql security invoker set search_path=public,pg_temp as $$
declare owner_id uuid:=auth.uid(); result public.income_receipts%rowtype;
begin
 if owner_id is null or p_expected_user_id is null or owner_id<>p_expected_user_id then raise exception 'Oturum doğrulanamadı';end if;
 if not exists(select 1 from public.income_sources where id=p_income_id and user_id=owner_id) then raise exception 'Gelir bulunamadı';end if;
 if p_actual_amount is null or p_actual_amount<0 or p_actual_amount>=1000000000000 or p_actual_amount<>round(p_actual_amount,2)
 or p_expected_amount is null or p_expected_amount<0 or p_expected_amount>=1000000000000 or p_expected_amount<>round(p_expected_amount,2)
 or p_is_received is null or p_note is null or length(p_note)>2000 then raise exception 'Gelir tutarı geçersiz';end if;
 insert into public.income_receipts(user_id,income_id,period_year,period_month,due_date,expected_amount,actual_amount,is_received,note)
 values(owner_id,p_income_id,p_period_year,p_period_month,p_due_date,p_expected_amount,p_actual_amount,p_is_received,p_note)
 on conflict(user_id,income_id,period_year,period_month) do update set actual_amount=excluded.actual_amount,is_received=excluded.is_received,note=excluded.note,updated_at=clock_timestamp()
 returning * into result;
 return to_jsonb(result);
end $$;
revoke all on function public.save_income_receipt(bigint,integer,integer,date,numeric,numeric,boolean,text,uuid) from public,anon;
grant execute on function public.save_income_receipt(bigint,integer,integer,date,numeric,numeric,boolean,text,uuid) to authenticated;
notify pgrst,'reload schema';
commit;
