-- Disposable database only. Not a production migration.
create role authenticated;
create role anon;
create schema if not exists auth;
create table if not exists auth.users(id uuid primary key,email text unique not null,email_confirmed_at timestamptz);
create or replace function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
grant usage on schema auth,public to authenticated,anon;
grant execute on function auth.uid() to authenticated,anon;
create schema family_local;
create table family_local.guard(name text primary key check(name='finown-family-local'));
insert into family_local.guard values('finown-family-local');
do $$ declare t text; begin
 foreach t in array array['banks','products','payments','income_sources','expense_sources','subscription_sources','subscription_payments','income_receipts','trackers','available_balances'] loop
  execute format('create table public.%I (id bigint generated by default as identity primary key,user_id uuid not null references auth.users,data jsonb not null)',t);
  execute format('alter table public.%I enable row level security',t);
  execute format('create policy local_finance_owner on public.%I for select to authenticated using(user_id=auth.uid())',t);
  execute format('grant select on public.%I to authenticated',t);
 end loop;
end $$;
